// Copies the ABIs the website needs from Foundry's out/ into web/src/abi/*.ts as `as const` arrays,
// so wagmi/viem infer argument and return types. Run after `forge build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = [
  "Lodestar",
  "LodestarFactory",
  "Exile",
  "Sandfall",
  "AscendSwapper",
  "IAscendLaunchpad",
  "IListingDesk",
  "MockERC20",
  // the launchpad adapters' shared shape and the Eleos, Kleos and Boxa hooks, for activations on those launchpads
  "V4FeeSource",
  "ILaunchpadHooks:IEleosHook",
  "ILaunchpadHooks:IKleosHook",
  "ILaunchpadHooks:IBoxaHook",
  // Ascend v5 on Elysium mainnet: its adapter, launchpad, per-pool escrow and seat contract
  "AscendV5FeeSource",
  "IAscendV5:IAscendV5Launchpad",
  "IAscendV5:IAscendV5Escrow",
  "IAscendV5:IAscendV5Seat",
];
const outDir = join(root, "web/src/abi");
mkdirSync(outDir, { recursive: true });

const index = [];
// "File:Contract" for a contract that shares its source file with others
for (const entry of contracts) {
  const [file, name = file] = entry.split(":");
  const artifact = JSON.parse(readFileSync(join(root, "out", `${file}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(outDir, `${name}.ts`),
    `// Generated by tools/export-abis.mjs. Do not edit.\nexport const ${id} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${id} } from "./${name}";`);
}
writeFileSync(join(outDir, "index.ts"), index.join("\n") + "\n");
console.log(`exported ${contracts.length} ABIs to web/src/abi`);
